function cmdbProvenance(timestamp: string): ProvenanceInfo {
  return { source: 'CMDB', timestamp };
}

function allCmdbProvenance(fields: string[], timestamp: string): Record<string, ProvenanceInfo> {
  return Object.fromEntries(fields.map((f) => [f, cmdbProvenance(timestamp)]));
}

